"""Start the middleware automatically at boot / logon, and restart it if it crashes.

* Linux   : systemd user unit (``~/.config/systemd/user/tango-mw.service``) + linger,
            so it starts at boot even without anyone logging in.
* Windows : scheduled task at logon running a small restart-loop script.
* macOS   : launchd agent (``~/Library/LaunchAgents``) with KeepAlive.

ROS 2 must be sourced in the same process: pass ``--ros-setup`` (detected automatically on
Linux when ``ROS_DISTRO`` is set).
"""
from __future__ import annotations

import os
import platform
import shlex
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional

NAME = "tango-mw"
WIN_TASK = "TangoMiddleware"
MAC_LABEL = "fr.projettango.middleware"


@dataclass
class Spec:
    workdir: Path
    config: Path
    python: str
    ros_setup: Optional[str] = None
    extra_args: str = ""

    def run_args(self) -> List[str]:
        return [self.python, "-m", "tango_mw", "run", "-c", str(self.config), *shlex.split(self.extra_args)]


def detect_ros_setup() -> Optional[str]:
    distro = os.environ.get("ROS_DISTRO")
    if distro and platform.system() != "Windows":
        p = Path(f"/opt/ros/{distro}/setup.bash")
        if p.exists():
            return str(p)
    return None


# --------------------------------------------------------------------------- file contents
def systemd_unit(s: Spec) -> str:
    cmd = " ".join(shlex.quote(a) for a in s.run_args())
    if s.ros_setup:
        cmd = f"source {shlex.quote(s.ros_setup)} && exec {cmd}"
    else:
        cmd = f"exec {cmd}"
    return f"""[Unit]
Description=Tango middleware (GAMA <-> robots)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory={s.workdir}
ExecStart=/bin/bash -lc {shlex.quote(cmd)}
Restart=always
RestartSec=3
Environment=PYTHONUNBUFFERED=1

[Install]
WantedBy=default.target
"""


def windows_script(s: Spec) -> str:
    args = " ".join(f'"{a}"' if " " in a or not a else a for a in s.run_args())
    ros = f'call "{s.ros_setup}"\r\n' if s.ros_setup else ""
    return (
        "@echo off\r\n"
        "rem Generated by `tango-mw service install`: restarts the middleware if it stops.\r\n"
        "title Tango middleware\r\n"
        f'cd /d "{s.workdir}"\r\n'
        f"{ros}"
        "set PYTHONIOENCODING=utf-8\r\n"
        ":loop\r\n"
        f"{args}\r\n"
        "echo Middleware stopped, restarting in 3 s...\r\n"
        "timeout /t 3 /nobreak >nul\r\n"
        "goto loop\r\n"
    )


def launchd_plist(s: Spec, log_dir: Path) -> str:
    cmd = " ".join(shlex.quote(a) for a in s.run_args())
    if s.ros_setup:
        cmd = f"source {shlex.quote(s.ros_setup)} && exec {cmd}"
    else:
        cmd = f"exec {cmd}"
    esc = lambda t: t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>{MAC_LABEL}</string>
  <key>ProgramArguments</key>
  <array><string>/bin/bash</string><string>-lc</string><string>{esc(cmd)}</string></array>
  <key>WorkingDirectory</key><string>{esc(str(s.workdir))}</string>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ThrottleInterval</key><integer>3</integer>
  <key>StandardOutPath</key><string>{esc(str(log_dir / "tango-mw.log"))}</string>
  <key>StandardErrorPath</key><string>{esc(str(log_dir / "tango-mw.log"))}</string>
</dict>
</plist>
"""


# --------------------------------------------------------------------------- install / uninstall
def _run(cmd: List[str], check: bool = True) -> subprocess.CompletedProcess:
    print("$", " ".join(cmd))
    return subprocess.run(cmd, check=check, text=True)


def install(s: Spec, dry_run: bool = False) -> int:
    system = platform.system()
    if system == "Linux":
        path = Path.home() / ".config" / "systemd" / "user" / f"{NAME}.service"
        content = systemd_unit(s)
    elif system == "Windows":
        path = s.config.parent / "tango-mw-service.cmd"
        content = windows_script(s)
    elif system == "Darwin":
        path = Path.home() / "Library" / "LaunchAgents" / f"{MAC_LABEL}.plist"
        content = launchd_plist(s, s.workdir / "logs")
    else:
        print(f"Unsupported system: {system}")
        return 1
    if dry_run:
        print(f"# {path}\n{content}")
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="" if system == "Windows" else None)
    print(f"Written: {path}")
    if system == "Linux":
        _run(["systemctl", "--user", "daemon-reload"])
        _run(["systemctl", "--user", "enable", "--now", f"{NAME}.service"])
        user = os.environ.get("USER", "")
        if _run(["loginctl", "enable-linger", user], check=False).returncode != 0:
            print(f"To start at boot without anyone logged in: sudo loginctl enable-linger {user}")
        print(f"Logs: journalctl --user -u {NAME} -f")
    elif system == "Windows":
        _run(["schtasks", "/Create", "/F", "/TN", WIN_TASK, "/SC", "ONLOGON", "/RL", "LIMITED",
              "/TR", f'cmd.exe /c "{path}"'])
        print("Starts automatically at logon. To start without anyone logging in, "
              "enable Windows automatic logon (netplwiz).")
        print(f"Start it now: schtasks /Run /TN {WIN_TASK}")
    else:
        (s.workdir / "logs").mkdir(exist_ok=True)
        _run(["launchctl", "unload", str(path)], check=False)
        _run(["launchctl", "load", "-w", str(path)])
        print(f"Logs: {s.workdir / 'logs' / 'tango-mw.log'}")
    return 0


def uninstall() -> int:
    system = platform.system()
    if system == "Linux":
        _run(["systemctl", "--user", "disable", "--now", f"{NAME}.service"], check=False)
        p = Path.home() / ".config" / "systemd" / "user" / f"{NAME}.service"
        p.unlink(missing_ok=True)
        _run(["systemctl", "--user", "daemon-reload"], check=False)
    elif system == "Windows":
        _run(["schtasks", "/Delete", "/F", "/TN", WIN_TASK], check=False)
    elif system == "Darwin":
        p = Path.home() / "Library" / "LaunchAgents" / f"{MAC_LABEL}.plist"
        _run(["launchctl", "unload", "-w", str(p)], check=False)
        p.unlink(missing_ok=True)
    return 0


def status() -> int:
    system = platform.system()
    if system == "Linux":
        return _run(["systemctl", "--user", "status", f"{NAME}.service"], check=False).returncode
    if system == "Windows":
        return _run(["schtasks", "/Query", "/TN", WIN_TASK, "/V", "/FO", "LIST"], check=False).returncode
    if system == "Darwin":
        return _run(["launchctl", "list", MAC_LABEL], check=False).returncode
    return 1


def spec_from_args(args) -> Spec:
    workdir = Path(args.workdir or Path.cwd()).resolve()
    config = Path(args.config) if args.config else workdir / "config" / "config.yaml"
    if not config.is_absolute():
        config = (workdir / config).resolve()
    return Spec(workdir=workdir, config=config, python=args.python or sys.executable,
                ros_setup=args.ros_setup or detect_ros_setup(), extra_args=args.args or "")
